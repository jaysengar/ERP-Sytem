-- Even connections made by an administrative owner switch to retail_app in
-- the adapter. FORCE RLS and that non-bypass role enforce business isolation.
DO $$
DECLARE table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['metadata','records','credentials','sessions','requests','audit'] LOOP
    EXECUTE format('ALTER TABLE retail.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('ALTER TABLE retail.%I FORCE ROW LEVEL SECURITY', table_name);
    EXECUTE format('CREATE POLICY workspace_scope ON retail.%I TO retail_app USING (workspace_id = nullif(current_setting(''retail.workspace_id'', true), '''')::uuid) WITH CHECK (workspace_id = nullif(current_setting(''retail.workspace_id'', true), '''')::uuid)', table_name);
  END LOOP;
  -- The trusted Node backend needs registry lookup before tenant selection.
  -- These policies never grant access to anon/authenticated/public roles.
  FOREACH table_name IN ARRAY ARRAY['workspaces','webhook_events','cancellation_requests','refund_requests','schema_migrations'] LOOP
    EXECUTE format('ALTER TABLE retail.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('ALTER TABLE retail.%I FORCE ROW LEVEL SECURITY', table_name);
    EXECUTE format('CREATE POLICY server_registry ON retail.%I TO retail_app USING (true) WITH CHECK (true)', table_name);
  END LOOP;
END $$;
REVOKE ALL ON ALL TABLES IN SCHEMA retail FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA retail FROM PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA retail TO retail_app;
REVOKE INSERT, UPDATE, DELETE ON retail.schema_migrations FROM retail_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA retail TO retail_app;
-- Supabase projects may have default grants for their Data API roles.
-- Revoke them explicitly in addition to keeping this schema private.
DO $$
DECLARE browser_role TEXT;
BEGIN
  FOREACH browser_role IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=browser_role) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA retail FROM %I', browser_role);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA retail FROM %I', browser_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA retail FROM %I', browser_role);
    END IF;
  END LOOP;
END $$;
