-- Run as the project's database administrator, using the migration command.
-- Kept outside "public": the browser/Supabase Data API gets no table access.
CREATE SCHEMA IF NOT EXISTS retail;
REVOKE ALL ON SCHEMA retail FROM PUBLIC;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'retail_app') THEN
    CREATE ROLE retail_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'retail_app' AND (rolsuper OR rolbypassrls OR rolcanlogin OR rolcreatedb OR rolcreaterole)) THEN
    RAISE EXCEPTION 'retail_app must be a restricted, non-login role';
  END IF;
  EXECUTE format('GRANT retail_app TO %I', current_user);
END $$;
GRANT USAGE ON SCHEMA retail TO retail_app;

CREATE TABLE retail.schema_migrations (version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE retail.workspaces (
  id UUID PRIMARY KEY, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL, owner_email TEXT NOT NULL UNIQUE,
  trial_end BIGINT NOT NULL, subscription_id TEXT UNIQUE, subscription_status TEXT,
  paid_until BIGINT NOT NULL DEFAULT 0, checkout_url TEXT, created_at BIGINT NOT NULL,
  cancel_pending INTEGER NOT NULL DEFAULT 0, billing_policy TEXT NOT NULL DEFAULT 'legacy_trial',
  first_payment_id TEXT UNIQUE, first_subscription_id TEXT, first_paid_at BIGINT, refund_deadline BIGINT
);
CREATE TABLE retail.webhook_events (id TEXT PRIMARY KEY, received_at BIGINT NOT NULL);
CREATE TABLE retail.cancellation_requests (
  workspace_id UUID NOT NULL REFERENCES retail.workspaces(id), subscription_id TEXT NOT NULL,
  requested_at BIGINT NOT NULL, kind TEXT, completed INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY(workspace_id, subscription_id)
);
CREATE TABLE retail.refund_requests (
  workspace_id UUID PRIMARY KEY REFERENCES retail.workspaces(id), subscription_id TEXT NOT NULL,
  payment_id TEXT NOT NULL, requested_at BIGINT NOT NULL, status TEXT NOT NULL, receipt TEXT NOT NULL,
  provider_refund_id TEXT, attempted_amount INTEGER, updated_at BIGINT NOT NULL
);

CREATE TABLE retail.metadata (
  id INTEGER NOT NULL CHECK(id=1), revision BIGINT NOT NULL, settings JSONB NOT NULL,
  workspace_id UUID NOT NULL DEFAULT nullif(current_setting('retail.workspace_id', true), '')::uuid REFERENCES retail.workspaces(id),
  PRIMARY KEY(workspace_id, id)
);
CREATE TABLE retail.records (
  kind TEXT NOT NULL CHECK(kind IN ('products','customers','suppliers','sales','purchases','expenses','staff','movements')),
  id TEXT NOT NULL, position INTEGER NOT NULL, data JSONB NOT NULL,
  workspace_id UUID NOT NULL DEFAULT nullif(current_setting('retail.workspace_id', true), '')::uuid REFERENCES retail.workspaces(id),
  PRIMARY KEY(workspace_id, kind, id)
);
CREATE UNIQUE INDEX product_sku ON retail.records(workspace_id, lower(data->>'sku')) WHERE kind='products';
CREATE UNIQUE INDEX product_barcode ON retail.records(workspace_id, (data->>'barcode')) WHERE kind='products';
CREATE UNIQUE INDEX sale_invoice ON retail.records(workspace_id, (data->>'invoice')) WHERE kind='sales';
CREATE UNIQUE INDEX staff_email ON retail.records(workspace_id, lower(data->>'email')) WHERE kind='staff';
CREATE INDEX products_category ON retail.records(workspace_id, (data->>'category')) WHERE kind='products';
CREATE INDEX records_order ON retail.records(workspace_id, kind, position);
CREATE TABLE retail.credentials (
  staff_id TEXT NOT NULL, password_hash TEXT NOT NULL,
  workspace_id UUID NOT NULL DEFAULT nullif(current_setting('retail.workspace_id', true), '')::uuid REFERENCES retail.workspaces(id),
  PRIMARY KEY(workspace_id, staff_id)
);
CREATE TABLE retail.sessions (
  token_hash TEXT NOT NULL, staff_id TEXT NOT NULL, expires BIGINT NOT NULL,
  workspace_id UUID NOT NULL DEFAULT nullif(current_setting('retail.workspace_id', true), '')::uuid REFERENCES retail.workspaces(id),
  PRIMARY KEY(workspace_id, token_hash),
  FOREIGN KEY(workspace_id, staff_id) REFERENCES retail.credentials(workspace_id, staff_id)
);
CREATE INDEX sessions_expiry ON retail.sessions(workspace_id, expires);
CREATE INDEX sessions_staff ON retail.sessions(workspace_id, staff_id);
CREATE TABLE retail.requests (
  actor TEXT NOT NULL, key TEXT NOT NULL, fingerprint TEXT NOT NULL, result JSONB NOT NULL,
  workspace_id UUID NOT NULL DEFAULT nullif(current_setting('retail.workspace_id', true), '')::uuid REFERENCES retail.workspaces(id),
  PRIMARY KEY(workspace_id, actor, key)
);
CREATE TABLE retail.audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY, actor TEXT NOT NULL, action TEXT NOT NULL,
  revision BIGINT NOT NULL, created_at TEXT NOT NULL,
  workspace_id UUID NOT NULL DEFAULT nullif(current_setting('retail.workspace_id', true), '')::uuid REFERENCES retail.workspaces(id),
  PRIMARY KEY(workspace_id, id)
);
CREATE INDEX audit_workspace_revision ON retail.audit(workspace_id, revision);
